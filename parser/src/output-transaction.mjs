import { createHash, randomUUID } from "node:crypto";
import { mkdir, readFile, readdir, rename, rm, stat, unlink, writeFile } from "node:fs/promises";
import path from "node:path";

import { assertFileFingerprint, fingerprintFile, pathExists, sha256File } from "./atomic.mjs";
import { compareSemanticVersions, isSemanticVersion } from "./semver.mjs";

const SHA256 = /^[0-9a-f]{64}$/u;

function contentHash(value) {
  return createHash("sha256").update(value).digest("hex");
}

function conversationSchema(value) {
  const match = /^(ai-chat-archive\/conversation\/(?:0|[1-9]\d*)\.(?:0|[1-9]\d*))\.(0|[1-9]\d*)$/u.exec(String(value || ""));
  return match ? { family: match[1], patch: Number(match[2]) } : null;
}

function compareSchemaVersions(left, right) {
  const leftSchema = conversationSchema(left);
  const rightSchema = conversationSchema(right);
  if (!leftSchema || !rightSchema || leftSchema.family !== rightSchema.family) return null;
  if (leftSchema.patch === rightSchema.patch) return 0;
  return leftSchema.patch < rightSchema.patch ? -1 : 1;
}

function throwIfAborted(signal, operation) {
  if (!signal?.aborted) return;
  const error = new Error(`${operation} was cancelled`);
  error.name = "AbortError";
  error.code = "ABORT_ERR";
  throw error;
}

async function assertExistingOutputIsNotNewer(targetPath, item, { signal = null } = {}) {
  let document;
  try {
    document = JSON.parse(signal
      ? await readFile(targetPath, { encoding: "utf8", signal })
      : await readFile(targetPath, "utf8"));
  } catch (error) {
    if (error?.name === "AbortError" || error?.code === "ABORT_ERR") throw error;
    return;
  }
  const hasParserVersion = Boolean(document) && Object.prototype.hasOwnProperty.call(document, "parser_version");
  const parserComparison = compareSemanticVersions(hasParserVersion ? document.parser_version : "", item.parserVersion);
  if (hasParserVersion && parserComparison === null) {
    throw new Error(`Refusing to replace a conversation with an unsupported Parser version: ${item.relativePath}`);
  }
  if (parserComparison === 1) {
    throw new Error(`Refusing to replace a conversation generated by newer Parser ${document.parser_version}: ${item.relativePath}`);
  }
  const schemaComparison = compareSchemaVersions(document?.schema, item.schema);
  const existingSchema = conversationSchema(document?.schema);
  const candidateSchema = conversationSchema(item.schema);
  if (existingSchema && candidateSchema && existingSchema.family !== candidateSchema.family) {
    throw new Error(`Refusing to replace conversation schema family ${document.schema} with ${item.schema}: ${item.relativePath}`);
  }
  if (schemaComparison === 1) {
    throw new Error(`Refusing to replace newer conversation schema ${document.schema}: ${item.relativePath}`);
  }
  if (document && Object.prototype.hasOwnProperty.call(document, "schema") && !conversationSchema(document.schema)) {
    throw new Error(`Refusing to replace an unsupported conversation schema: ${item.relativePath}`);
  }
}

function safeStem(fileName) {
  const extension = path.extname(fileName);
  const raw = path.basename(fileName, extension)
    .normalize("NFC")
    .replace(/[<>:"/\\|?*\u0000-\u001f]/gu, "_")
    .replace(/[. ]+$/gu, "")
    .trim();
  return Array.from(raw || "conversation").slice(0, 120).join("");
}

function outputIdentity(candidate, sourceSha256, multiple) {
  const conversationKey = String(
    candidate?.conversationKey
    || candidate?.conversationId
    || candidate?.conversation?.conversation_key
    || candidate?.conversation?.conversation_id
    || ""
  ).toLowerCase();
  if (conversationKey) {
    if (!SHA256.test(conversationKey)) throw new TypeError("conversation_key must be a lowercase privacy-preserving SHA-256 identity");
    return conversationKey;
  }
  if (multiple) throw new TypeError("Every conversation from a one-to-many input must have conversation_key");
  return sourceSha256;
}

function relativeOutput(fileName) {
  return `Conversations/${fileName}`;
}

function resolveOutput(paths, relativePath) {
  const normalized = String(relativePath || "").replaceAll("\\", "/");
  const segments = normalized.split("/");
  if (segments[0] !== "Conversations" || segments.length < 2 || !segments.at(-1).toLowerCase().endsWith(".json")
    || segments.some((segment) => !segment || segment === "." || segment === "..")) {
    throw new TypeError(`Unsafe conversation output path: ${relativePath}`);
  }
  const absolute = path.resolve(paths.root, ...normalized.split("/"));
  const inside = path.relative(path.resolve(paths.conversations), absolute);
  if (!inside || path.isAbsolute(inside) || inside === ".." || inside.startsWith(`..${path.sep}`)) {
    throw new TypeError(`Conversation output escapes its directory: ${relativePath}`);
  }
  return absolute;
}

function chooseOutputNames({
  inputName,
  sourceSha256,
  candidates,
  previousOutputs,
  forceMultiple = false
}) {
  const stem = safeStem(inputName);
  const multiple = forceMultiple || candidates.length > 1;
  const identities = new Set();
  const fileNames = new Set();
  const previousByIdentity = new Map(
    (previousOutputs || []).map((output) => [String(output.conversation_key || output.conversation_id || "").toLowerCase(), output])
  );
  return candidates.map((candidate) => {
    const conversationKey = outputIdentity(candidate, sourceSha256, multiple);
    if (identities.has(conversationKey)) throw new Error(`Duplicate conversation identity from ${inputName}: ${conversationKey}`);
    identities.add(conversationKey);
    const previous = previousByIdentity.get(conversationKey)
      || (!multiple && previousOutputs?.length === 1 ? previousOutputs[0] : null);
    let fileName = previous
      ? path.basename(previous.path)
      : multiple
        ? `${stem}--${conversationKey.slice(0, 16)}.json`
        : `${stem}.json`;
    if (fileNames.has(fileName)) fileName = `${stem}--${conversationKey}.json`;
    if (fileNames.has(fileName)) throw new Error(`Duplicate conversation output name from ${inputName}: ${fileName}`);
    fileNames.add(fileName);
    const relativePath = previous?.path || relativeOutput(fileName);
    return { ...candidate, conversationKey, fileName, relativePath };
  });
}

async function chooseNonOverwritingOutput({
  paths,
  inputName,
  sourcePath,
  item,
  previousPaths,
  ownership,
  reserved,
  signal = null
}) {
  const tryPath = async (relativePath) => {
    throwIfAborted(signal, "Conversation output collision check");
    if (reserved.has(relativePath)) return null;
    const owner = ownership.get(relativePath);
    if (owner && owner !== sourcePath) return null;
    const targetPath = resolveOutput(paths, relativePath);
    let collisionKnownAbsent = false;
    if (!previousPaths.has(relativePath) && owner !== sourcePath) {
      if (await pathExists(targetPath)) return null;
      collisionKnownAbsent = true;
    }
    reserved.add(relativePath);
    return {
      ...item,
      fileName: path.basename(relativePath),
      relativePath,
      targetPath,
      collisionKnownAbsent
    };
  };

  const preferred = await tryPath(item.relativePath);
  if (preferred) return preferred;

  const stem = safeStem(inputName);
  const sourceIdentity = createHash("sha256").update(sourcePath).digest("hex").slice(0, 12);
  const conversationIdentity = item.conversationKey.slice(0, 16);
  const candidates = [
    `${stem}--${conversationIdentity}.json`,
    `${stem}--${conversationIdentity}--${sourceIdentity}.json`
  ];
  for (const fileName of candidates) {
    const selected = await tryPath(relativeOutput(fileName));
    if (selected) return selected;
  }
  for (let counter = 2; counter <= 10000; counter += 1) {
    const fileName = `${stem}--${conversationIdentity}--${sourceIdentity}--${counter}.json`;
    const selected = await tryPath(relativeOutput(fileName));
    if (selected) return selected;
  }
  throw new Error(`Unable to choose a non-overwriting conversation output path for ${inputName}`);
}

export function outputOwnership(parseState) {
  const ownership = new Map();
  for (const source of parseState.sources || []) {
    for (const output of source.outputs || []) {
      const previous = ownership.get(output.path);
      if (previous && previous !== source.path) throw new Error(`Parse state assigns ${output.path} to multiple inputs`);
      ownership.set(output.path, source.path);
    }
  }
  return ownership;
}

export async function createConversationOutputBatch({
  paths,
  inputName,
  sourcePath,
  sourceSha256,
  previousOutputs = [],
  ownership = new Map(),
  forceMultiple = false,
  retainPreviousOutputs = false,
  now = new Date()
}) {
  const token = `${process.pid}-${randomUUID()}`;
  const stageDirectory = path.join(paths.conversations, `.cloudig-stage-${token}`);
  const backupLabel = `${now.toISOString().replace(/[:.]/gu, "-")}--${sourceSha256.slice(0, 12)}--${token.slice(-8)}`;
  const backupDirectory = path.join(paths.backups, backupLabel);
  await mkdir(paths.conversations, { recursive: true });
  await mkdir(paths.backups, { recursive: true });
  await mkdir(stageDirectory, { recursive: false });
  const staged = [];
  let closed = false;
  let planned = null;

  async function stage({
    conversationKey = "",
    conversationId = "",
    serialized,
    schema = "",
    parserVersion = "",
    parserAdapter = null,
    exporterVersion = "",
    signal = null
  }) {
    throwIfAborted(signal, "Conversation output stage");
    if (closed) throw new Error("Conversation output batch is already closed");
    if (planned) throw new Error("Conversation output batch is already planned");
    const normalizedSchema = String(schema || "").trim();
    const normalizedParserVersion = String(parserVersion || "").trim();
    const normalizedParserAdapter = parserAdapter && typeof parserAdapter === "object" && !Array.isArray(parserAdapter)
      ? { id: String(parserAdapter.id || "").trim(), version: String(parserAdapter.version || "").trim() }
      : null;
    const originalExporterVersion = String(exporterVersion || "");
    if (!normalizedSchema) throw new TypeError("Staged conversation output requires its schema");
    if (!conversationSchema(normalizedSchema)) throw new TypeError("Staged conversation output requires a supported conversation schema identifier");
    if (!isSemanticVersion(normalizedParserVersion)) {
      throw new TypeError("Staged conversation output requires a semantic Parser version");
    }
    if (!normalizedParserAdapter
      || !/^[a-z0-9][a-z0-9._-]{0,127}$/u.test(normalizedParserAdapter.id)
      || !isSemanticVersion(normalizedParserAdapter.version)) {
      throw new TypeError("Staged conversation output requires an exact Parser adapter id and semantic version");
    }
    if (originalExporterVersion && !originalExporterVersion.trim()) {
      throw new TypeError("Staged conversation output exporter version must contain a non-whitespace character");
    }
    if (originalExporterVersion.length > 128 || /[\u0000-\u001f]/u.test(originalExporterVersion)) {
      throw new TypeError("Staged conversation output exporter version must be a readable version");
    }
    const value = String(serialized);
    const stagePath = path.join(stageDirectory, `candidate-${String(staged.length).padStart(8, "0")}.json`);
    await writeFile(stagePath, value, { encoding: "utf8", flag: "wx", ...(signal ? { signal } : {}) });
    throwIfAborted(signal, "Conversation output stage");
    staged.push({
      conversationKey: String(conversationKey || conversationId || "").toLowerCase(),
      stagePath,
      sizeBytes: Buffer.byteLength(value),
      sha256: contentHash(value),
      schema: normalizedSchema,
      parserVersion: normalizedParserVersion,
      parserAdapter: normalizedParserAdapter,
      exporterVersion: originalExporterVersion
    });
    return staged.length;
  }

  async function abort() {
    if (closed) return;
    closed = true;
    await rm(stageDirectory, { recursive: true, force: true });
  }

  async function plan({ signal = null } = {}) {
    throwIfAborted(signal, "Conversation output plan");
    if (closed) throw new Error("Conversation output batch is already closed");
    if (planned) {
      throwIfAborted(signal, "Conversation output plan");
      return planned.public;
    }
    const preliminary = chooseOutputNames({
      inputName,
      sourceSha256,
      candidates: staged,
      previousOutputs,
      forceMultiple
    });
    const selected = [];
    const reserved = new Set();
    const previousPaths = new Set((previousOutputs || []).map((output) => output.path));
    for (const item of preliminary) {
      selected.push(await chooseNonOverwritingOutput({
        paths,
        inputName,
        sourcePath,
        item,
        previousPaths,
        ownership,
        reserved,
        signal
      }));
    }
    const newPaths = new Set(selected.map((item) => item.relativePath));
    const obsolete = retainPreviousOutputs ? [] : previousOutputs.filter((item) => !newPaths.has(item.path));
    const outputs = retainPreviousOutputs
      ? previousOutputs.filter((item) => !newPaths.has(item.path)).map((item) => ({ ...item }))
      : [];
    for (const item of selected) {
      throwIfAborted(signal, "Conversation output plan");
      const targetExists = item.collisionKnownAbsent ? false : await pathExists(item.targetPath);
      let modifiedAt;
      if (targetExists) {
        await assertExistingOutputIsNotNewer(item.targetPath, item, { signal });
        const information = await stat(item.targetPath);
        const currentSha256 = await sha256File(item.targetPath, { signal });
        item.precondition = Object.freeze({
          target: item.targetPath,
          exists: true,
          sizeBytes: information.size,
          sha256: currentSha256
        });
        const unchanged = information.size === item.sizeBytes && currentSha256 === item.sha256;
        if (!unchanged) {
          const owner = ownership.get(item.relativePath);
          const previouslyOwned = previousOutputs.some((output) => output.path === item.relativePath);
          if (owner !== sourcePath && !previouslyOwned) throw new Error(`Refusing to replace an unowned file: ${item.relativePath}`);
        }
        modifiedAt = unchanged ? information.mtime.toISOString() : (await stat(item.stagePath)).mtime.toISOString();
      } else {
        item.precondition = Object.freeze({ target: item.targetPath, exists: false });
        modifiedAt = (await stat(item.stagePath)).mtime.toISOString();
      }
      item.modifiedAt = modifiedAt;
      outputs.push({
        conversation_key: item.conversationKey,
        path: item.relativePath,
        size_bytes: item.sizeBytes,
        modified_at: modifiedAt,
        sha256: item.sha256,
        schema: item.schema,
        parser_version: item.parserVersion,
        parser_adapter: item.parserAdapter,
        ...(item.exporterVersion ? { exporter_version: item.exporterVersion } : {})
      });
    }
    const plannedObsolete = [];
    for (const item of obsolete) {
      throwIfAborted(signal, "Conversation output plan");
      const targetPath = resolveOutput(paths, item.path);
      if (!await pathExists(targetPath)) {
        plannedObsolete.push({ ...item, targetPath, precondition: Object.freeze({ target: targetPath, exists: false }) });
        continue;
      }
      const information = await stat(targetPath);
      if (!information.isFile()) throw new TypeError(`Obsolete conversation output is not a file: ${item.path}`);
      plannedObsolete.push({
        ...item,
        targetPath,
        precondition: Object.freeze({
          target: targetPath,
          exists: true,
          sizeBytes: information.size,
          sha256: await sha256File(targetPath, { signal })
        })
      });
    }
    outputs.sort((left, right) => left.path.localeCompare(right.path, "en"));
    const publicPlan = Object.freeze({
      targets: Object.freeze(selected.map((item) => Object.freeze({
        conversation_key: item.conversationKey,
        path: item.relativePath,
        targetPath: item.targetPath,
        sizeBytes: item.sizeBytes,
        sha256: item.sha256
      }))),
      obsolete: Object.freeze(plannedObsolete.map((item) => Object.freeze({
        path: item.path,
        targetPath: resolveOutput(paths, item.path)
      }))),
      preconditions: Object.freeze([
        ...selected.map((item) => item.precondition),
        ...plannedObsolete.map((item) => item.precondition)
      ]),
      outputs: Object.freeze(outputs.map((item) => Object.freeze({ ...item }))),
      stageDirectory,
      rollbackCleanupPaths: Object.freeze([stageDirectory, backupDirectory]),
      stagedBytes: selected.reduce((total, item) => total + item.sizeBytes, 0)
    });
    planned = { selected, obsolete: plannedObsolete, outputs, public: publicPlan };
    return publicPlan;
  }

  async function commit({ signal = null } = {}) {
    throwIfAborted(signal, "Conversation output commit");
    if (closed) throw new Error("Conversation output batch is already closed");
    await plan({ signal });
    closed = true;
    const { selected, obsolete, outputs } = planned;
    const movedPrevious = [];
    const installed = [];
    const statuses = [];
    let backupCreated = false;
    let rolledBack = false;

    async function ensureBackupDirectory() {
      if (!backupCreated) {
        await mkdir(backupDirectory, { recursive: false });
        backupCreated = true;
      }
    }

    async function rollbackWrites() {
      if (rolledBack) return;
      rolledBack = true;
      const conflicts = [];
      const matches = (current, expected) => current.exists === expected.exists
        && (!current.exists || (
          current.regularFile === true
          && current.stable !== false
          && current.sizeBytes === expected.sizeBytes
          && current.sha256 === expected.sha256
        ));
      for (const item of installed.reverse()) {
        const current = await fingerprintFile(item.targetPath);
        if (matches(current, item.before)) continue;
        if (!matches(current, item.expected)) {
          conflicts.push(`${path.basename(item.targetPath)}:unknown-installed-state`);
          continue;
        }
        const displaced = path.join(
          path.dirname(item.targetPath),
          `.${path.basename(item.targetPath)}.cloudig-rollback-${process.pid}-${randomUUID()}`
        );
        try {
          await rename(item.targetPath, displaced);
        } catch {
          conflicts.push(`${path.basename(item.targetPath)}:changed-before-capture`);
          continue;
        }
        const captured = await fingerprintFile(displaced);
        if (!matches(captured, item.expected)) {
          if (!await pathExists(item.targetPath)) {
            try { await rename(displaced, item.targetPath); } catch { /* preserve sidecar on conflict */ }
          }
          conflicts.push(`${path.basename(item.targetPath)}:changed-during-capture`);
          continue;
        }
        try { await unlink(displaced); } catch { /* captured bytes are this batch's installed output */ }
      }
      for (const item of movedPrevious.reverse()) {
        const current = await fingerprintFile(item.targetPath);
        if (matches(current, item.before)) continue;
        if (current.exists) {
          conflicts.push(`${path.basename(item.targetPath)}:unknown-restore-state`);
          continue;
        }
        const backup = await fingerprintFile(item.backupPath);
        if (!matches(backup, item.before)) {
          conflicts.push(`${path.basename(item.targetPath)}:backup-mismatch`);
          continue;
        }
        try {
          await rename(item.backupPath, item.targetPath);
        } catch {
          conflicts.push(`${path.basename(item.targetPath)}:changed-before-restore`);
        }
      }
      if (conflicts.length) {
        const error = new Error(`Conversation output rollback preserved concurrent content: ${conflicts.join(", ")}`);
        error.code = "CLOUDIG_OUTPUT_ROLLBACK_CONFLICT";
        error.conflicts = Object.freeze([...conflicts]);
        throw error;
      }
    }

    try {
      try {
        for (const item of selected) {
          throwIfAborted(signal, "Conversation output commit");
          await assertFileFingerprint(item.targetPath, item.precondition, {
            signal,
            operation: "Conversation output optimistic-concurrency precondition"
          });
          const targetExists = await pathExists(item.targetPath);
          if (targetExists) {
            await assertExistingOutputIsNotNewer(item.targetPath, item, { signal });
            const information = await stat(item.targetPath);
            if (information.size === item.sizeBytes && await sha256File(item.targetPath, { signal }) === item.sha256) {
              await unlink(item.stagePath);
              statuses.push("unchanged");
              continue;
            }
            const owner = ownership.get(item.relativePath);
            const previouslyOwned = previousOutputs.some((output) => output.path === item.relativePath);
            if (owner !== sourcePath && !previouslyOwned) throw new Error(`Refusing to replace an unowned file: ${item.relativePath}`);
            await ensureBackupDirectory();
            const backupPath = path.join(backupDirectory, item.fileName);
            await assertFileFingerprint(item.targetPath, item.precondition, {
              signal,
              operation: "Conversation output final optimistic-concurrency precondition"
            });
            await rename(item.targetPath, backupPath);
            movedPrevious.push({ targetPath: item.targetPath, backupPath, before: item.precondition });
            throwIfAborted(signal, "Conversation output commit");
            statuses.push("replaced");
          } else {
            statuses.push("created");
          }
          await assertFileFingerprint(item.targetPath, { exists: false }, {
            signal,
            operation: "Conversation output installation precondition"
          });
          await mkdir(path.dirname(item.targetPath), { recursive: true });
          await rename(item.stagePath, item.targetPath);
          installed.push({
            targetPath: item.targetPath,
            before: item.precondition,
            expected: Object.freeze({
              exists: true,
              sizeBytes: item.sizeBytes,
              sha256: item.sha256
            })
          });
          throwIfAborted(signal, "Conversation output commit");
        }

        for (const oldOutput of obsolete) {
          throwIfAborted(signal, "Conversation output commit");
          const targetPath = oldOutput.targetPath;
          await assertFileFingerprint(targetPath, oldOutput.precondition, {
            signal,
            operation: "Obsolete output optimistic-concurrency precondition"
          });
          if (!await pathExists(targetPath)) continue;
          await ensureBackupDirectory();
          const backupPath = path.join(backupDirectory, `obsolete-${path.basename(targetPath)}`);
          await assertFileFingerprint(targetPath, oldOutput.precondition, {
            signal,
            operation: "Obsolete output final optimistic-concurrency precondition"
          });
          await rename(targetPath, backupPath);
          movedPrevious.push({ targetPath, backupPath, before: oldOutput.precondition });
          throwIfAborted(signal, "Conversation output commit");
          statuses.push("replaced");
        }
      } catch (error) {
        await rollbackWrites();
        throw error;
      }

      if (backupCreated && !(await readdir(backupDirectory)).length) await rm(backupDirectory, { recursive: false, force: true });
      throwIfAborted(signal, "Conversation output commit");
      const uniqueStatuses = new Set(statuses);
      const writeStatus = uniqueStatuses.size === 0 || (uniqueStatuses.size === 1 && uniqueStatuses.has("unchanged"))
        ? "unchanged"
        : uniqueStatuses.size === 1
          ? [...uniqueStatuses][0]
          : "mixed";
      return Object.freeze({
        outputs: outputs.map((item) => ({ ...item })),
        writeStatus,
        backup: backupCreated ? `Data/Backups/${backupLabel}` : ""
      });
    } catch (error) {
      await rollbackWrites();
      throw error;
    } finally {
      await rm(stageDirectory, { recursive: true, force: true });
    }
  }

  return Object.freeze({ stage, plan, commit, abort, get count() { return staged.length; } });
}

export async function writeConversationBatch(options) {
  const batch = await createConversationOutputBatch(options);
  try {
    for (const candidate of options.candidates || []) {
      await batch.stage({
        conversationKey: candidate.conversationKey
          || candidate.conversationId
          || candidate.conversation?.conversation_key
          || candidate.conversation?.conversation_id
          || "",
        serialized: candidate.serialized,
        schema: candidate.schema || candidate.conversation?.schema,
        parserVersion: candidate.parserVersion || candidate.parser_version,
        parserAdapter: candidate.parserAdapter || candidate.parser_adapter || candidate.conversation?.parser_adapter,
        exporterVersion: candidate.exporterVersion || candidate.exporter_version,
        signal: options.signal || null
      });
    }
    return await batch.commit({ signal: options.signal || null });
  } catch (error) {
    await batch.abort();
    throw error;
  }
}
